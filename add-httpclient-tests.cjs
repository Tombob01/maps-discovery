const fs = require('fs');

const content = [
'/**',
' * tests/unit/ui/httpClient.listRecords.test.ts',
' *',
' * Unit tests for httpClient.listRecords() pagination loop.',
' * Uses a mock fetch to simulate multi-page API responses.',
' */',
'import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";',
'',
'// ---------------------------------------------------------------------------',
'// Helpers',
'// ---------------------------------------------------------------------------',
'',
'function makeRecord(i: number) {',
'  return {',
'    id: `biz-${i}`,',
'    name: `Business ${i}`,',
'    phone: null,',
'    normalizedPhone: null,',
'    website: null,',
'    city: "Lagos",',
'    country: "Nigeria",',
'    primaryCategory: null,',
'    rating: null,',
'    sourceProvider: "google-maps",',
'  };',
'}',
'',
'function makePageResponse(allItems: ReturnType<typeof makeRecord>[], page: number, pageSize: number) {',
'  const start = (page - 1) * pageSize;',
'  const items = allItems.slice(start, start + pageSize);',
'  const hasMore = start + pageSize < allItems.length;',
'  return { ok: true, data: { items, total: allItems.length, page, hasMore } };',
'}',
'',
'// ---------------------------------------------------------------------------',
'// Tests',
'// ---------------------------------------------------------------------------',
'',
'describe("httpClient.listRecords() — pagination loop", () => {',
'  const PAGE_SIZE = 100;',
'',
'  beforeEach(() => {',
'    vi.stubGlobal("fetch", vi.fn());',
'  });',
'',
'  afterEach(() => {',
'    vi.unstubAllGlobals();',
'  });',
'',
'  async function runListRecords(totalRecords: number): Promise<number> {',
'    const allItems = Array.from({ length: totalRecords }, (_, i) => makeRecord(i));',
'    let callCount = 0;',
'    (globalThis.fetch as ReturnType<typeof vi.fn>).mockImplementation(async (url: string) => {',
'      const u = new URL(url);',
'      const page = Number(u.searchParams.get("page") ?? "1");',
'      const pageSize = Number(u.searchParams.get("pageSize") ?? "100");',
'      callCount++;',
'      const body = makePageResponse(allItems, page, pageSize);',
'      return { ok: true, json: async () => body };',
'    });',
'    const { httpClient } = await import("../../../src/ui/lib/httpClient.js");',
'    const records = await httpClient.listRecords("run-test-001");',
'    return records.length;',
'  }',
'',
'  it("returns all 118 records across 2 pages", async () => {',
'    const count = await runListRecords(118);',
'    expect(count).toBe(118);',
'    const fetchMock = globalThis.fetch as ReturnType<typeof vi.fn>;',
'    expect(fetchMock).toHaveBeenCalledTimes(2);',
'  });',
'',
'  it("returns all 501 records across 6 pages", async () => {',
'    const count = await runListRecords(501);',
'    expect(count).toBe(501);',
'    const fetchMock = globalThis.fetch as ReturnType<typeof vi.fn>;',
'    expect(fetchMock).toHaveBeenCalledTimes(6);',
'  });',
'',
'  it("returns all 1000 records across 10 pages", async () => {',
'    const count = await runListRecords(1000);',
'    expect(count).toBe(1000);',
'    const fetchMock = globalThis.fetch as ReturnType<typeof vi.fn>;',
'    expect(fetchMock).toHaveBeenCalledTimes(10);',
'  });',
'',
'  it("stops fetching when hasMore is false", async () => {',
'    const count = await runListRecords(50);',
'    expect(count).toBe(50);',
'    const fetchMock = globalThis.fetch as ReturnType<typeof vi.fn>;',
'    // 50 records fits in one page — only 1 fetch',
'    expect(fetchMock).toHaveBeenCalledTimes(1);',
'  });',
'',
'  it("returns empty array when run has no records", async () => {',
'    const count = await runListRecords(0);',
'    expect(count).toBe(0);',
'  });',
'});',
].join('\n');

fs.mkdirSync('tests/unit/ui', { recursive: true });
fs.writeFileSync('tests/unit/ui/httpClient.listRecords.test.ts', content, 'utf8');
console.log('OK');
